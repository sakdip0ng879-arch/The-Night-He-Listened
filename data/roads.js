/* ═══ builder — สร้าง TK.routes ให้ engine ในรูปแบบเดิมทุกประการ ═══════════ */
(function(){
  const N = TK.nodes, E = TK.edges;

  /* ── ★ ดึงพิกัดจาก places.js (DECISIONS กฎ 4 — พิกัดเดียวทั้งโปรเจกต์) ──
     node ที่ไม่ได้ประกาศ x/y เอง ต้องมี id ตรงกับสถานที่ใน TK.places
     ถ้าหาไม่เจอ ให้ **ดังทันทีตอนโหลด** ไม่ใช่ปล่อยให้ลูกศรไปโผล่ที่ (undefined,undefined)
     ซึ่งจะกลายเป็นเส้นหายเงียบ ๆ แบบ BUGS_SEEN §D2 */
  const P = (TK.places || {});
  const orphan = [];
  for (const id in N){
    const n = N[id];
    if (n.x == null || n.y == null){
      const p = P[id];
      if (!p){ orphan.push(id); continue; }
      n.x = p.x; n.y = p.y;
      if (n.type == null) n.type = p.type;
      if (n.chk == null && p.chk) n.chk = true;
      if (n.label == null) n.label = p.label;
    }
  }
  if (orphan.length){
    const msg = 'roads.js: node ที่หาพิกัดไม่เจอใน places.js — ' + orphan.join(', ');
    if (typeof console !== 'undefined') console.error(msg);
    throw new Error(msg);
  }

  /* ดัชนี edge สองทาง — ถนนเส้นเดียวกันเดินได้สองทิศ ไม่ต้องประกาศซ้ำ
     (นี่คือเหตุผลที่ธง `reverse` บน route ถูกยกเลิก — กลับ array ก็ได้เส้นถอย) */
  const idx = {};
  const key = (a,b) => a + '\0' + b;
  E.forEach(e => { idx[key(e.a,e.b)] = e; idx[key(e.b,e.a)] = e; });
  TK.edgeIndex = idx;

  /* ── ★ ประกอบเส้นทางแบบ "สุ่มจุดแล้วลบมุม" (เขียนใหม่ 2026-08-25) ─────────
     ของเดิมต่อสตริง path ของแต่ละ edge เข้าด้วยกันตรง ๆ (joinD + reverseD)
     ผลคือรอยต่อระหว่าง edge เป็น **มุมแหลม** — เห็นชัดสุดที่ด่านคู่ Baishui→Yangping
     ที่เส้นวกกลับ ~120° จนเจ้าของทักว่า "หักงอแปลก ๆ" ทั้งที่ลำดับจุดถูกต้อง
     (ถนนจริงก็หักตรงนั้น แต่ถนนจริงหักแบบมีรัศมีวงเลี้ยว ไม่ใช่หักศอกเป็นเข็ม)

     วิธีใหม่: สุ่มจุดตามเส้นของทุก edge (คณิตล้วน ไม่ง้อ DOM — สูตรเดียวกับ
     samplePath ใน check_routes) · เดินสวนทาง = กลับลำดับ array จบ ·
     แล้วลบมุมเฉพาะ **ที่รอยต่อ node** ด้วยโค้ง Q รัศมี ~12 หน่วย
     (โค้งภายใน edge ที่ลากมือไว้ไม่ถูกแตะ — จุดสุ่มถี่พอที่รูปเดิมคงอยู่)

     ✔ หัว-ท้ายเส้นตรงจุด node เป๊ะเหมือนเดิม (test_roads ข้อ 4 วัดอยู่)
     ✔ ผู้บริโภคทุกตัวอ่าน d แบบดึงตัวเลข (routeEnd · seasonBox · check_map)
       ซึ่งรับ polyline ได้ตรง ๆ — จุดแรก/จุดสุดท้ายยังเป็นปลายทางจริง
     ✘ joinD กับ reverseD ถูกถอดทิ้ง — แผลเป็นของ joinD ยังอยู่ใน BUGS_SEEN §E1 */
  const SAMPLE_STEP = 7;      /* หน่วยแผนที่ต่อหนึ่งจุดสุ่ม */
  const R_JUNC = 12;          /* รัศมีลบมุมที่รอยต่อ node */

  function samplePts(d){
    const t = d.match(/[MLCQ]|[-+]?[0-9]*\.?[0-9]+/gi); if (!t) return [];
    const out = []; let i = 0, cur = null, cmd = null;
    const push = p => { if (!out.length ||
      Math.hypot(p[0]-out[out.length-1][0], p[1]-out[out.length-1][1]) > 0.01) out.push(p); };
    while (i < t.length){
      if (/[MLCQ]/i.test(t[i])){ cmd = t[i].toUpperCase(); i++; continue; }
      if (cmd === 'M'){ cur = [+t[i], +t[i+1]]; i += 2; push(cur); continue; }
      if (cmd === 'L'){ const q = [+t[i], +t[i+1]]; i += 2;
        const n = Math.max(1, Math.ceil(Math.hypot(q[0]-cur[0], q[1]-cur[1]) / SAMPLE_STEP));
        for (let k = 1; k <= n; k++) push([cur[0]+(q[0]-cur[0])*k/n, cur[1]+(q[1]-cur[1])*k/n]);
        cur = q; continue; }
      if (cmd === 'Q'){ const c1 = [+t[i], +t[i+1]], q = [+t[i+2], +t[i+3]]; i += 4;
        const est = Math.hypot(c1[0]-cur[0], c1[1]-cur[1]) + Math.hypot(q[0]-c1[0], q[1]-c1[1]);
        const n = Math.max(6, Math.ceil(est / SAMPLE_STEP));
        for (let k = 1; k <= n; k++){ const u = k/n, v = 1-u;
          push([v*v*cur[0] + 2*v*u*c1[0] + u*u*q[0], v*v*cur[1] + 2*v*u*c1[1] + u*u*q[1]]); }
        cur = q; continue; }
      if (cmd === 'C'){ const c1 = [+t[i], +t[i+1]], c2 = [+t[i+2], +t[i+3]], q = [+t[i+4], +t[i+5]]; i += 6;
        const est = Math.hypot(c1[0]-cur[0], c1[1]-cur[1]) + Math.hypot(c2[0]-c1[0], c2[1]-c1[1]) +
                    Math.hypot(q[0]-c2[0], q[1]-c2[1]);
        const n = Math.max(8, Math.ceil(est / SAMPLE_STEP));
        for (let k = 1; k <= n; k++){ const u = k/n, v = 1-u;
          push([v*v*v*cur[0] + 3*v*v*u*c1[0] + 3*v*u*u*c2[0] + u*u*u*q[0],
                v*v*v*cur[1] + 3*v*v*u*c1[1] + 3*v*u*u*c2[1] + u*u*u*q[1]]); }
        cur = q; continue; }
      i++;
    }
    return out;
  }

  /* placeholder สำหรับ edge ที่ยังไม่ได้ลาก — **เส้นตรงต่อจุด** (เจ้าของเคาะ 2026-08-25)
     เดิมเป็นเส้นโก่งเล็กน้อย ซึ่งคือการ "แกล้งทำเป็นถนนจริง" ทั้งที่ยังไม่มีใครลาก
     เส้นตรงพูดความจริงกว่า: ช่วงนี้คือ "เดินจากจุดถึงจุด ยังไม่ได้ลากตามภูมิประเทศ"
     พอ edge ไหนถูกลาก `d` จริง (ตามหุบเขา/สันเขา) มันจะโค้งเองตามธรรมชาติ —
     ภาพจึงบอกสถานะงานไปในตัว: ตรง = งานค้าง (check_routes นับให้) · โค้ง = ลากแล้ว
     มุมที่จุดต่อถูกลบด้วย R_JUNC อยู่แล้ว เส้นตรงจึงอ่านเป็นแผนภาพต่อจุดที่เรียบร้อย */
  function stubPts(p, q){
    const L = Math.hypot(q.x - p.x, q.y - p.y) || 1;
    const out = []; const n = Math.max(4, Math.ceil(L / SAMPLE_STEP));
    for (let k = 0; k <= n; k++){ const u = k / n;
      out.push([p.x + (q.x - p.x) * u, p.y + (q.y - p.y) * u]); }
    return out;
  }

  /* ลบมุมที่รอยต่อ: แทนหัวมุมด้วยโค้ง Q — รัศมีหดเองเมื่อรอยต่อชิดกัน/ชิดปลายเส้น */
  function roundJunctions(pts, junc){
    const n = pts.length;
    const f = p => p[0].toFixed(1) + ',' + p[1].toFixed(1);
    if (n < 2) return '';
    const cum = [0];
    for (let k = 1; k < n; k++)
      cum[k] = cum[k-1] + Math.hypot(pts[k][0]-pts[k-1][0], pts[k][1]-pts[k-1][1]);
    const total = cum[n-1];
    const at = s => {
      if (s <= 0) return pts[0];
      if (s >= total) return pts[n-1];
      let k = 1; while (cum[k] < s) k++;
      const t = (s - cum[k-1]) / ((cum[k] - cum[k-1]) || 1);
      return [pts[k-1][0] + (pts[k][0]-pts[k-1][0])*t, pts[k-1][1] + (pts[k][1]-pts[k-1][1])*t];
    };
    const js = junc.filter(k => k > 0 && k < n - 1).sort((a,b) => a - b);
    const marks = [0].concat(js.map(k => cum[k]), [total]);
    const rs = js.map((k, i) => Math.min(R_JUNC,
      (marks[i+1] - marks[i]) * 0.45, (marks[i+2] - marks[i+1]) * 0.45));

    let d = 'M ' + f(pts[0]);
    let k = 1;
    for (let ji = 0; ji <= js.length; ji++){
      const stopS = ji < js.length ? cum[js[ji]] - rs[ji] : total;
      while (k < n && cum[k] < stopS - 0.01){ d += ' L ' + f(pts[k]); k++; }
      if (ji < js.length){
        const jk = js[ji], s = cum[jk], r = rs[ji];
        if (r > 0.8){
          d += ' L ' + f(at(s - r)) + ' Q ' + f(pts[jk]) + ' ' + f(at(s + r));
          while (k < n && cum[k] <= s + r + 0.01) k++;
        } else {
          d += ' L ' + f(pts[jk]);
          while (k < n && cum[k] <= s + 0.01) k++;
        }
      } else if (cum[n-1] - (k > 1 ? cum[k-1] : 0) > 0.01 || k < n){
        d += ' L ' + f(pts[n-1]);           /* ปลายเส้นต้องจบที่จุดสุดท้ายเป๊ะ */
      }
    }
    return d;
  }

  TK.routes = {};
  TK.routeMeta = {};

  for (const id in TK.marches){
    const m = TK.marches[id];
    const missing = [], untraced = [];
    let li = 0, wagons = true;
    let pts = [], junc = [];

    for (let i = 0; i < m.path.length - 1; i++){
      const a = m.path[i], b = m.path[i+1];
      const e = idx[key(a,b)];
      if (!e){ missing.push(a + ' → ' + b); continue; }
      li += e.li || 0;
      if (e.wagons === false) wagons = false;

      let leg;
      if (e.d){
        leg = samplePts(e.d);
        if (e.a !== a) leg.reverse();        /* เดินสวนทาง = กลับลำดับจุด */
      } else {
        const p = N[a], q = N[b];
        if (!p || !q){ missing.push(a + ' → ' + b + ' (ไม่มีพิกัด)'); continue; }
        leg = stubPts(p, q);                 /* วางตามทิศที่เดินจริงอยู่แล้ว */
        untraced.push(a + '–' + b);
      }
      if (pts.length){
        const last = pts[pts.length-1], first = leg[0];
        /* หัวท้ายต่อกันจริง (check_routes ยืนยัน) → ตัดจุดซ้ำ แล้วจำตำแหน่งรอยต่อไว้ลบมุม */
        if (Math.hypot(last[0]-first[0], last[1]-first[1]) < 0.5){
          junc.push(pts.length - 1);
          leg = leg.slice(1);
        }
      }
      pts = pts.concat(leg);
    }

    TK.routes[id]   = { label: m.label, d: roundJunctions(pts, junc) };
    TK.routeMeta[id]= { side:m.side, commander:m.commander, troops:m.troops,
                        supply:!!m.supply, path:m.path, li, wagons, missing, untraced };
  }
})();
